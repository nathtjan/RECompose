"""Generates src/RECompose.App/Theme/Icons.g.cs from design/icons/*.svg.

Usage: python3 tools/icons/generate.py [--check]

Each icon becomes a list of (path data, filled) shapes on the 24 × 24 grid. Paths, rects
and circles are supported (that is all the icon set uses). Shapes with fill="currentColor"
are filled; the rest are stroked at 2 px with round caps and joins, as drawn.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "icons"
TARGET = ROOT / "src" / "RECompose.App" / "Theme" / "Icons.g.cs"
NS = "{http://www.w3.org/2000/svg}"


def num(v: str) -> float:
    return float(v)


def fmt(v: float) -> str:
    return ("%.3f" % v).rstrip("0").rstrip(".")


def rect_path(e) -> str:
    x, y = num(e.get("x", "0")), num(e.get("y", "0"))
    w, h = num(e.get("width")), num(e.get("height"))
    r = min(num(e.get("rx", e.get("ry", "0"))), w / 2, h / 2)
    if r <= 0:
        return f"M{fmt(x)},{fmt(y)} h{fmt(w)} v{fmt(h)} h{fmt(-w)} z"
    return (f"M{fmt(x + r)},{fmt(y)} h{fmt(w - 2 * r)} a{fmt(r)},{fmt(r)} 0 0 1 {fmt(r)},{fmt(r)} "
            f"v{fmt(h - 2 * r)} a{fmt(r)},{fmt(r)} 0 0 1 {fmt(-r)},{fmt(r)} h{fmt(-(w - 2 * r))} "
            f"a{fmt(r)},{fmt(r)} 0 0 1 {fmt(-r)},{fmt(-r)} v{fmt(-(h - 2 * r))} a{fmt(r)},{fmt(r)} 0 0 1 {fmt(r)},{fmt(-r)} z")


def circle_path(e) -> str:
    cx, cy, r = num(e.get("cx", "0")), num(e.get("cy", "0")), num(e.get("r"))
    return (f"M{fmt(cx - r)},{fmt(cy)} a{fmt(r)},{fmt(r)} 0 1 0 {fmt(2 * r)},0 "
            f"a{fmt(r)},{fmt(r)} 0 1 0 {fmt(-2 * r)},0 z")


def shapes(svg_path: pathlib.Path):
    root = ET.parse(svg_path).getroot()
    default_fill = root.get("fill", "none")
    for e in root.iter():
        tag = e.tag.replace(NS, "")
        if tag == "svg":
            continue
        fill = e.get("fill", default_fill)
        filled = fill not in ("none", "")
        if tag == "path":
            data = re.sub(r"\s+", " ", e.get("d")).strip()
        elif tag == "rect":
            data = rect_path(e)
        elif tag == "circle":
            data = circle_path(e)
        else:
            raise ValueError(f"{svg_path.name}: unsupported element {tag}")
        yield data, filled


def generate() -> str:
    lines = [
        "// <auto-generated>",
        "// Generated by tools/icons/generate.py from design/icons. Do not edit by hand.",
        "// </auto-generated>",
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "#nullable enable",
        "namespace RECompose.App.Theme;",
        "",
        "public static class IconData",
        "{",
        "    public static readonly IReadOnlyDictionary<string, (string Data, bool Filled)[]> All =",
        "        new Dictionary<string, (string Data, bool Filled)[]>",
        "        {",
    ]
    for svg in sorted(SOURCE.glob("*.svg")):
        items = ", ".join(f'("{d}", {"true" if f else "false"})' for d, f in shapes(svg))
        lines.append(f'            ["{svg.stem}"] = [{items}],')
    lines += ["        };", "}", ""]
    return "\n".join(lines)


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date. Run: python3 tools/icons/generate.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
